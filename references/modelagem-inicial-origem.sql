CREATE TYPE "PapelUsuario" AS ENUM (
  'COMPRADOR',
  'ARTESAO',
  'CURADOR',
  'ADMIN'
);

CREATE TYPE "StatusPeca" AS ENUM (
  'DISPONIVEL',
  'RESERVADA',
  'VENDIDA',
  'ARQUIVADA'
);

CREATE TYPE "StatusPedido" AS ENUM (
  'PENDENTE_PAGAMENTO',
  'APROVADO',
  'RECUSADO'
);

CREATE TYPE "StatusLogistico" AS ENUM (
  'AGUARDANDO_POSTAGEM',
  'POSTADO',
  'EM_TRANSITO',
  'ENTREGUE',
  'CANCELADO_POR_ATRASO'
);

CREATE TYPE "StatusRepasse" AS ENUM (
  'RETIDO_EM_CUSTODIA',
  'CONGELADO_POR_DISPUTA',
  'LIQUIDADO_PIX'
);

CREATE TYPE "TipoDisputa" AS ENUM (
  'AVARIA_TRANSPORTE',
  'ARREPENDIMENTO_LEGAL'
);

CREATE TYPE "StatusDisputa" AS ENUM (
  'EM_ANALISE',
  'ESTORNADO_COMPRADOR',
  'RECUSADA'
);

CREATE TABLE "usuarios" (
  "id" uuid PRIMARY KEY DEFAULT (gen_random_uuid()),
  "nome" varchar NOT NULL,
  "email" varchar UNIQUE NOT NULL,
  "cpf_cnpj" varchar UNIQUE NOT NULL,
  "telefone_whatsapp" varchar,
  "senha_hash" varchar NOT NULL,
  "status" varchar DEFAULT 'ATIVO',
  "criado_em" timestamp DEFAULT (now())
);

CREATE TABLE "usuarios_papeis" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" uuid,
  "papel" "PapelUsuario" NOT NULL
);

CREATE TABLE "recuperacoes_senha" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" uuid,
  "token_hash" varchar NOT NULL,
  "expira_em" timestamp NOT NULL
);

CREATE TABLE "artesaos" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" uuid UNIQUE,
  "biografia_cultural" text,
  "chave_pix_criptografada" varchar NOT NULL
);

CREATE TABLE "atelies" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "artesao_id" int UNIQUE,
  "nome_comercial" varchar NOT NULL,
  "polo_cultural" varchar NOT NULL,
  "status" varchar DEFAULT 'ATIVO'
);

CREATE TABLE "atelies_curadores" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "atelie_id" int,
  "usuario_id" uuid
);

CREATE TABLE "enderecos" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "cep" varchar(8) NOT NULL,
  "logradouro" varchar NOT NULL,
  "numero" varchar NOT NULL,
  "complemento" varchar,
  "bairro" varchar NOT NULL,
  "cidade" varchar NOT NULL,
  "uf" varchar(2) NOT NULL,
  "atelie_id" int UNIQUE,
  "usuario_id" uuid
);

CREATE TABLE "pecas" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "atelie_id" int,
  "titulo" varchar NOT NULL,
  "descricao" text NOT NULL,
  "tipologia" varchar NOT NULL,
  "preco" decimal(10,2) NOT NULL,
  "peso_gramas" int NOT NULL,
  "comprimento_cm" int NOT NULL,
  "largura_cm" int NOT NULL,
  "altura_cm" int NOT NULL,
  "is_fragil" boolean DEFAULT false,
  "quantidade_estoque" int NOT NULL DEFAULT 1,
  "status" "StatusPeca" DEFAULT 'DISPONIVEL'
);

CREATE TABLE "fotos_peca" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "peca_id" int,
  "url" varchar NOT NULL,
  "is_principal" boolean DEFAULT false
);

CREATE TABLE "reservas" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "peca_id" int UNIQUE,
  "usuario_id" uuid,
  "quantidade" int NOT NULL,
  "expira_em" timestamp NOT NULL,
  "status" varchar DEFAULT 'ATIVA'
);

CREATE TABLE "pedidos" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" uuid,
  "endereco_entrega_id" int,
  "valor_total_pecas" decimal(10,2) NOT NULL,
  "valor_total_frete" decimal(10,2) NOT NULL,
  "valor_total_pedido" decimal(10,2) NOT NULL,
  "status" "StatusPedido" DEFAULT 'PENDENTE_PAGAMENTO',
  "metodo_pagamento" varchar,
  "idempotency_key" varchar UNIQUE,
  "criado_em" timestamp DEFAULT (now())
);

CREATE TABLE "subpedidos" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "pedido_id" int,
  "atelie_id" int,
  "valor_frete_subpedido" decimal(10,2) NOT NULL,
  "status_logistico" "StatusLogistico" DEFAULT 'AGUARDANDO_POSTAGEM',
  "codigo_rastreio" varchar,
  "data_limite_postagem" timestamp,
  "data_postagem" timestamp,
  "data_entrega" timestamp
);

CREATE TABLE "itens_subpedido" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "subpedido_id" int,
  "peca_id" int,
  "quantidade" int NOT NULL,
  "preco_unitario_historico" decimal(10,2) NOT NULL,
  "comissao_plataforma_historica" decimal(10,2) NOT NULL
);

CREATE TABLE "repasses_pix" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "subpedido_id" int UNIQUE,
  "artesao_id" int,
  "valor_bruto" decimal(10,2) NOT NULL,
  "taxa_plataforma" decimal(10,2) NOT NULL,
  "valor_liquido" decimal(10,2) NOT NULL,
  "chave_pix_historica" varchar NOT NULL,
  "status" "StatusRepasse" DEFAULT 'RETIDO_EM_CUSTODIA',
  "data_previsao_liberacao" timestamp,
  "codigo_end_to_end_bacen" varchar
);

CREATE TABLE "disputas" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "subpedido_id" int UNIQUE,
  "tipo" "TipoDisputa" NOT NULL,
  "descricao" text,
  "urls_fotos" text,
  "codigo_postagem_reversa" varchar,
  "status" "StatusDisputa" DEFAULT 'EM_ANALISE',
  "aberta_em" timestamp DEFAULT (now())
);

CREATE TABLE "logs_notificacoes" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "usuario_id" uuid,
  "canal" varchar NOT NULL,
  "mensagem" text NOT NULL,
  "data_envio" timestamp DEFAULT (now()),
  "status" varchar
);

